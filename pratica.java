
public class pratica {
    public static void main(String[] args) {
        // System.out.print - Não possui quebras de linha
        // Sytem.out.println - Possui quebras de linhas
        System.out.print("Esse é um exemplo de saída de dados na Linguagem Java.");
        System.out.println("Esse é um exemplo de saída de dados sem quabra de linhas em Java.");

        // Delacração de Variáveis em Java
        // <tipo> <nome> = <valor da variável>

        double idade  = 35.0;
        System.out.println(idade);

    }
}

